const wait=[];
const ctx={storage,waitUntil(p){wait.push(p)}};
const room=new SignalingRoom(ctx,{});
async function api(path,body){
 const r=await room.api(new Request('https://test.example'+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}));
 return {status:r.status,data:await r.json()};
}
await storage.put('user:alice',{username:'alice'});
await storage.put('user:bob',{username:'bob'});
await storage.put('user:mallory',{username:'mallory'});
await storage.put('friends:alice',['bob']);
await storage.put('friends:bob',['alice']);
const alice=await room.createSession('alice'), bob=await room.createSession('bob');
const device='A'.repeat(140);
assert.equal((await api('/api/push/register',{deviceToken:device})).status,401);
assert.equal((await api('/api/push/register',{token:bob,deviceToken:'short'})).status,400);
assert.equal((await api('/api/push/register',{token:bob,deviceToken:device})).status,200);
assert.deepEqual(map.get('fcmTokens:bob'),[device]);
assert.equal(map.get('fcmTokens:alice'),undefined);
console.log('PASS push token registration requires authentication and belongs only to recipient');
