import assert from 'node:assert/strict';
import fs from 'node:fs';
import {webcrypto} from 'node:crypto';
globalThis.crypto ??=webcrypto;
const source=fs.readFileSync(new URL('../cloudflare-site/src/worker.js',import.meta.url),'utf8').replace('import { DurableObject } from "cloudflare:workers";','class DurableObject {}');
const {SignalingRoom}=await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(source));
const data=new Map(),messageReads=[];
const storage={async get(k){if(k.startsWith('messages:'))messageReads.push(k);return structuredClone(data.get(k))},async put(k,v){data.set(k,structuredClone(v))},async delete(k){data.delete(k)}};
const room=new SignalingRoom({storage,getWebSockets:()=>[]},{});
for(const name of ['alice','bob','carol','dave','erin'])data.set('user:'+name,{username:name,displayName:name,email:'PRIVATE@example.com',passwordHash:'PRIVATE',cover:'large-unneeded-cover',accountHidden:true});
data.set('friends:alice',['bob','carol','dave','erin']);
for(const name of ['bob','carol','erin'])data.set('friends:'+name,['alice']);
data.set('blocked:carol',['alice']);data.get('user:erin').disabled=true;
const messages=Array.from({length:200},(_,i)=>({id:String(i),from:'bob',to:'alice',text:'x'.repeat(500),mediaType:'image',media:'A'.repeat(20000),ts:i+1}));
messages.push({id:'signal',from:'bob',to:'alice',mediaType:'call-signal',media:'PRIVATE_SDP',ts:999});
data.set('messages:alice:bob',messages);
for(const name of ['carol','dave','erin'])data.set('messages:alice:'+name,[{text:'FORBIDDEN'}]);
const token=await room.createSession('alice');
const get=async (query)=>{const r=await room.api(new Request('https://unit.test/api/inbox?'+query));return{status:r.status,headers:r.headers,body:await r.json()}};
assert.equal((await get('peers=bob')).status,401);
const result=await get('token='+token+'&peers=bob,bob,carol,dave,erin,alice,unknown');
assert.equal(result.status,200);assert.equal(result.body.summaries.length,1);
assert.equal(result.body.summaries[0].user.username,'bob');assert.equal(result.body.summaries[0].lastMessage.id,'199');
assert.equal(result.body.summaries[0].lastMessage.text.length,160);
const serialized=JSON.stringify(result.body);
assert.ok(!serialized.includes('PRIVATE')&&!serialized.includes('FORBIDDEN')&&!serialized.includes('unneeded-cover'));
assert.ok(serialized.length<1000,'no media bodies or conversation history in the preview');
assert.deepEqual(messageReads,['messages:alice:bob'],'only authorized, deduplicated conversations are read');
assert.equal(data.get('messages:alice:bob')[0].deliveredAt,undefined,'preview does not mark unseen history delivered');
assert.equal(result.headers.get('cache-control'),'no-store');
assert.equal((await get('token='+token+'&peers='+Array.from({length:51},(_,i)=>'peer'+i).join(','))).status,400);
assert.equal((await get('token='+token+'&peers=..%2Fprivate')).status,400);
assert.equal((await get('token='+token+'&peers='+('a'.repeat(4001)))).status,400);
data.set('messages:alice:bob',[{id:'call',mediaType:'call-event',from:'bob',to:'alice',callType:'video',callStatus:'completed',ts:20}]);
const call=(await get('token='+token+'&peers=bob')).body.summaries[0].lastMessage;
assert.equal(call.callType,'video');assert.equal(call.callStatus,'completed');
console.log('PASS inbox: one compact authorized preview, no full histories/attachments/secrets, mutual friendship and blocks enforced, deduplication/caps and call status preserved');
